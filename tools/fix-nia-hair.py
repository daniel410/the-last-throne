"""Derive only Nia's connected hairstyle; keep the v4 source immutable."""
import copy, hashlib, json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'assets/npcs/heads-v4/heads.json'
r=copy.deepcopy(json.loads(source.read_text())['characters']['nia'])
r['parts']=[p for p in r['parts'] if p['name']!='SweptForelock']
def sphere(name,size,position,roll=0):
    r['parts'].append(dict(name=name,size=size,position=position,color='352D30',roll=roll,kind='sphere'))
sphere('CrownBridge',[1.38,.48,1.12],[0,5.75,.06])
sphere('SweptForelock',[1.15,.38,.56],[-.20,5.66,-.37],.28)
sphere('BraidRoot',[.44,.82,.58],[-.71,5.30,-.18],-.12)
for p in r['parts']:
    if p['name']=='FrontBraid':
        p['position'][0]=round(p['position'][0]-.16,6)
        p['position'][2]=round(p['position'][2]+.12,6)
    elif p['name']=='BraidTie':
        p['position']=[-.866,3.84,-.68]
r['revision']='nia-connected-hair-v5'
out=ROOT/'assets/npcs/nia-hair-v5/recipe.json'
out.write_text(json.dumps(r,indent=2)+'\n')
def lua(v):
    if isinstance(v,dict):return '{'+','.join('['+json.dumps(k)+']='+lua(x) for k,x in v.items())+'}'
    if isinstance(v,list):return '{'+','.join(map(lua,v))+'}'
    return json.dumps(v)
(ROOT/'src/shared/NPCHeadAssets/nia.luau').write_text('-- Generated by tools/fix-nia-hair.py; Nia-only v5 derivation.\nreturn '+lua(r)+'\n')
manifest={'id':r['revision'],'source':'assets/npcs/heads-v4/heads.json','sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'recipeSha256':hashlib.sha256(out.read_bytes()).hexdigest(),'parts':len(r['parts']),'unchanged':'face, head, ears, body, identity, quests and other NPCs'}
(ROOT/'assets/npcs/nia-hair-v5/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest))
