"""Blender MCP에서 추출한 원본 CFrame을 런타임 데이터로 변환한다."""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parents[1]
source = root / 'assets/models/deepwood-architecture-blender-v1/kit.json'
data = json.loads(source.read_text())

def literal(value):
    if isinstance(value, list):
        return '{' + ','.join(map(literal, value)) + '}'
    if isinstance(value, float):
        return format(value, '.9g')
    return json.dumps(value, ensure_ascii=True, separators=(',', ':'))

lines = ['-- Generated by tools/export-deepwood-architecture.py from Blender MCP.', 'return {']
for name, parts in data['models'].items():
    lines.append(' ' + name + '={')
    for p in parts:
        assert len(p['cf']) == 12 and all(v > 0 for v in p['size'])
        row = [p[k] for k in ['name', 'shape', 'material', 'size', 'color', 'cf', 'solid']]
        lines.append('  ' + literal(row) + ',')
    lines.append(' },')
lines.append('}')
(root / 'src/server/World/DeepwoodArchitectureTemplates.luau').write_text('\n'.join(lines) + '\n')
print(json.dumps({'models': len(data['models']), 'parts': sum(map(len, data['models'].values())), 'sha256': hashlib.sha256(source.read_bytes()).hexdigest()}))
