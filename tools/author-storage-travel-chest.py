"""Author one compact travel chest; the same geometry drives Roblox and Blender."""
import json, math, random
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/models/storage-travel-chest-v1'
OUT.mkdir(parents=True,exist_ok=True)
parts=[]
def part(name,size,at,color,material='Wood',shape='Block',angle=0,solid=False):
 parts.append(dict(name=name,size=size,position=at,color=color,material=material,shape=shape,angle=angle,solid=solid))
wood=[(104,75,47),(116,85,53),(96,68,42),(124,92,58),(109,78,47)]
iron=(60,57,52);rust=(85,65,47);leather=(103,67,39);seam=(47,34,24)
part('Chest',(5.6,2.8,3.05),(0,1.4,0),seam,solid=True)
for row in range(5):
 y=.31+row*.54
 for front in [-1,1]:
  part('WoodPlank',(5.6,.51,.09),(0,y,front*1.55),wood[(row+(front==1))%5])
 for side in [-1,1]:
  part('EndPlank',(.09,.51,3.1),(side*2.82,y,0),wood[(row+2)%5])
# A dark lid joint, then separate planks instead of a gift-box cap.
part('LidJoint',(5.78,.10,3.23),(0,2.85,0),seam)
for col in range(7):
 part('LidPlank',(.80,.30,3.20),(-2.46+col*.82,3.05,0),wood[(col+1)%5])
for y in [.43,2.29]:
 for z in [-1.64,1.64]:part('IronRail',(5.86,.23,.09),(0,y,z),iron,'Metal')
 for x in [-2.93,2.93]:part('EndIronRail',(.09,.23,3.35),(x,y,0),iron,'Metal')
for x in [-2.73,2.73]:
 for z in [-1.65,1.65]:part('CornerIron',(.36,2.82,.10),(x,1.42,z),iron,'Metal')
for x in [-2.94,2.94]:
 for z in [-1.43,1.43]:part('CornerReturn',(.10,2.82,.37),(x,1.42,z),iron,'Metal')
for x in [-2.68,2.68]:
 for z in [-1.38,1.38]:part('LidCornerCap',(.5,.11,.51),(x,3.24,z),iron,'Metal')
for x in [-1.72,1.72]:
 for z in [-1.72,1.72]:part('LeatherStrap',(.25,3.12,.075),(x,1.65,z),leather,'Fabric')
 part('LidLeatherStrap',(.25,.07,3.50),(x,3.26,0),leather,'Fabric')
 # Forged rectangular buckle surrounding the leather; never gold ribbon.
 for dx in [-.19,.19]:part('BuckleSide',(.065,.40,.10),(x+dx,1.92,1.80),iron,'Metal')
 for y in [1.72,2.12]:part('BuckleRail',(.44,.065,.10),(x,y,1.80),iron,'Metal')
 part('BuckleTongue',(.055,.32,.075),(x,1.95,1.86),rust,'Metal')
 for y in [.74,.98,1.22]:part('StrapHole',(.045,.055,.012),(x,y,1.764),seam,'SmoothPlastic')
for x0 in [-1.5,1.5]:
 x1,y0,y1=0,1.55,.53
 dx,dy=x1-x0,y1-y0
 part('DiagonalTravelHarness',(.20,math.hypot(dx,dy),.065),((x0+x1)/2,(y0+y1)/2,1.73),leather,'Fabric',angle=-math.atan2(dx,dy))
# Broad worn rivets, not polished jewels.
for z in [-1.71,1.71]:
 for y in [.43,2.29]:
  for x in [-2.73,-1.08,0,1.08,2.73]:part('IronRivet',(.115,.115,.07),(x,y,z),rust,'Metal','Ball')
for x in [-3.00,3.00]:
 for y in [.43,2.29]:
  for z in [-1.38,0,1.38]:part('EndRivet',(.07,.115,.115),(x,y,z),rust,'Metal','Ball')
part('LockHasp',(.32,1.0,.12),(0,2.52,1.77),iron,'Metal')
for y in [2.19,2.68]:part('HaspRivet',(.13,.13,.07),(0,y,1.86),rust,'Metal','Ball')
part('Padlock',(.64,.68,.23),(0,1.47,1.94),iron,'Metal')
for x in [-.23,.23]:part('LockShackle',(.09,.37,.10),(x,1.96,1.91),iron,'Metal')
for i in range(6):
 a=(i+.5)*math.pi/6
 part('ShackleArch',(.09,.15,.1),(.23*math.cos(a),2.13+.23*math.sin(a),1.91),iron,'Metal',angle=a-math.pi/2)
part('Keyhole',(.08,.10,.013),(0,1.50,2.062),seam,'SmoothPlastic','Ball')
part('KeyholeStem',(.04,.14,.013),(0,1.41,2.062),seam,'SmoothPlastic')
for x in [-3.01,3.01]:
 for z in [-.49,.49]:part('HandleBracket',(.12,.32,.24),(x,1.61,z),iron,'Metal')
 for z in [-.42,.42]:part('HandleUpright',(.12,.35,.10),(x*1.015,1.43,z),iron,'Metal')
 part('CarryingGrip',(.14,.13,.94),(x*1.015,1.24,0),leather,'Fabric')
for x in [-1.3,1.3]:part('RearHinge',(.4,.6,.12),(x,2.73,-1.75),iron,'Metal')
# Sparse physical splits in the wood retain readability without new texture assets.
rng=random.Random(61101)
for row in range(5):
 for i in range(3):
  part('WoodSplit',(rng.uniform(.18,.55),.014,.009),(rng.uniform(-2.25,2.25),.25+row*.54+rng.uniform(-.12,.12),1.601),seam)
for i in range(7):part('LidWear',(.025,.008,rng.uniform(.4,1.2)),(-2.40+i*.80,3.204,rng.uniform(-.5,.5)),seam)
(OUT/'geometry.json').write_text(json.dumps({'id':'storage-travel-chest-v1','dimensions':[6.25,3.3,3.9],'parts':parts},indent=2)+'\n')
# Numeric data only: no external textures, assets or executable model content.
def lua(v):
 if isinstance(v,str):return json.dumps(v)
 if isinstance(v,bool):return 'true' if v else 'false'
 if isinstance(v,(tuple,list)):return '{'+','.join(lua(x) for x in v)+'}'
 if isinstance(v,dict):return '{'+','.join(k+'='+lua(x) for k,x in v.items())+'}'
 return str(round(v,6))
(ROOT/'src/shared/StorageChestGeometry.luau').write_text('-- Generated by tools/author-storage-travel-chest.py; editable source geometry is preserved.\nreturn '+lua(parts)+'\n')
print(json.dumps({'parts':len(parts),'geometry':str(OUT/'geometry.json')}))
