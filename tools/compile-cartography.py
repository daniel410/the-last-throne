"""Compile the isolated world bake into merged, bounded GUI footprints (no uploads)."""
import argparse, json, re, hashlib
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--log',type=Path,required=True);p.add_argument('--output',type=Path,default=Path('src/shared/CampaignCartography.luau'));a=p.parse_args()
raw=a.log.read_text();complete=re.search(r'CARTOGRAPHY_COMPLETE (\d+) (\d+)',raw);assert complete,'bake did not finish'
n=int(complete[1]);zones={key:json.loads(value)for key,value in re.findall(r'CARTOGRAPHY_DATA_ZONE ([\w-]+) (\{[^\n]+\})',raw)}
assert len(zones)==int(complete[2])==44
data={'resolution':n,'zones':zones}
lines=['-- Generated by tools/export-cartography-native.luau + tools/compile-cartography.py.', '-- Real top-down scenery footprints; regenerate after world geometry changes.', 'return {resolution='+str(n)+',zones={']
stats={}
for key,z in sorted(data['zones'].items()):
    pixels=z['pixels'];assert len(pixels)==n*n
    # The exact route vectors replace quantized road pixels.
    pixels=[1 if v==2 else v for v in pixels];used=set();rects=[]
    for y in range(n):
        for x in range(n):
            k=y*n+x;c=pixels[k]
            if k in used or c in (0,1):continue
            w=1
            while x+w<n and y*n+x+w not in used and pixels[y*n+x+w]==c:w+=1
            h=1
            while y+h<n and all((y+h)*n+xx not in used and pixels[(y+h)*n+xx]==c for xx in range(x,x+w)):h+=1
            for yy in range(y,y+h):
                for xx in range(x,x+w):used.add(yy*n+xx)
            rects.append([x,y,w,h,c])
    def lua(v):
        if isinstance(v,str):return json.dumps(v)
        if isinstance(v,(list,tuple)):return '{'+','.join(lua(x)for x in v)+'}'
        return str(round(v,3))
    lines.append('['+lua(key)+']={landmark='+lua(z.get('landmark',key))+',spawn='+lua(z['spawn'])+',rects='+lua(rects)+',roads='+lua(z['roads'])+'},')
    stats[key]={'rectangles':len(rects),'roads':len(z['roads'])}
lines.append('}}\n');a.output.write_text('\n'.join(lines));print(json.dumps({'zones':len(stats),'sourceSha256':hashlib.sha256(json.dumps(data,sort_keys=True).encode()).hexdigest(),'regions':stats},indent=2))
