"""Generate the runtime catalog from the reviewed NPC source, without image OCR."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT / "assets/npcs/cast-v1/catalog.json").read_text())
entries = source["characters"]
assert len(entries) == len({v["id"] for v in entries}) == 30
lines = ["-- Generated by tools/build-npc-catalog.py; edit assets/npcs/cast-v1/catalog.json.",
         "local Catalog={version=1,characters={},byId={},byRegion={}}"]
for entry in entries:
    fields = ",".join(f"{key}={json.dumps(value)}" for key, value in entry.items())
    lines.append("table.insert(Catalog.characters,{" + fields + "})")
lines += ["for _,c in ipairs(Catalog.characters) do",
          " Catalog.byId[c.id]=c;Catalog.byRegion[c.region]=Catalog.byRegion[c.region] or {};table.insert(Catalog.byRegion[c.region],c)",
          "end", "return Catalog", ""]
(ROOT / "src/shared/NPCCatalog.luau").write_text("\n".join(lines))
