"""Derive quiver colors from approved bow base-color images (requires Pillow)."""
import collections
import hashlib
import io
import json
from pathlib import Path
import struct
from PIL import Image

root = Path(__file__).resolve().parents[1]
base = root / 'assets/models/four-family-weapons-meshy-v1'
records = [(base / r['source'], r['textureAssetId']) for r in json.loads((base / 'manifest.json').read_text())['records'] if r['classId'] == 'elf']
records.append((root / 'assets/shared/td-player-weapons/source/ElfBow-td-derived-review.glb', 'rbxassetid://115101390772936'))
lines = ['-- Generated by tools/derive-elf-quiver-palette.py from approved sRGB bow textures.', 'return {']
report = []
for path, texture in records:
    data = path.read_bytes()
    size = struct.unpack_from('<I', data, 12)[0]
    doc = json.loads(data[20:20 + size])
    binary = data[28 + size:]
    material = doc['materials'][0]['pbrMetallicRoughness']
    image_index = doc['textures'][material['baseColorTexture']['index']]['source']
    view = doc['bufferViews'][doc['images'][image_index]['bufferView']]
    offset = view.get('byteOffset', 0)
    image = Image.open(io.BytesIO(binary[offset:offset + view['byteLength']])).convert('RGB')
    image.thumbnail((256, 256))
    bins = collections.defaultdict(list)
    for pixel in image.get_flattened_data():
        if max(pixel) - min(pixel) > 25 and 60 < max(pixel) < 245:
            bins[tuple(c // 32 for c in pixel)].append(pixel)
    ranked = sorted(bins.values(), key=len, reverse=True)
    def average(pixels):
        return tuple(round(sum(p[i] for p in pixels) / len(pixels)) for i in range(3))
    body = average(ranked[0])
    trim = next((average(group) for group in ranked[1:] if sum((a-b)**2 for a,b in zip(average(group), body)) > 100**2), body)
    lines.append(f' ["{texture}"]={{body=Color3.fromRGB{body},trim=Color3.fromRGB{trim}}},')
    report.append(dict(source=str(path.relative_to(root)), sha256=hashlib.sha256(data).hexdigest(), texture=texture, body=body, trim=trim))
lines.append('}')
(root / 'src/server/Cosmetics/ElfQuiverPalette.luau').write_text('\n'.join(lines) + '\n')
print(json.dumps(report, indent=2))
