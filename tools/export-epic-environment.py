"""Generate runtime data from Blender MCP's exact sRGB primitive export."""
from pathlib import Path
import json,hashlib
root=Path(__file__).resolve().parents[1]
source=root/'assets/models/epic-environment-v1/kit.json'
data=json.loads(source.read_text())
lines=['-- Generated by tools/export-epic-environment.py; edit the Blender authoring source.','return {']
for name,parts in data['models'].items():
 lines.append(' '+name+'={')
 for p in parts:
  row=[p['name'],p['shape'],p['material'],p['position'],p['size'],p['color'],p['yaw'],p['lean']]
  text=json.dumps(row,separators=(',',':')).replace('[','{').replace(']','}')
  lines.append('  '+text+',')
 lines.append(' },')
lines.append('}')
(root/'src/server/World/EpicDetailTemplates.luau').write_text('\n'.join(lines)+'\n')
print(json.dumps({'models':len(data['models']),'parts':sum(map(len,data['models'].values())),'sha256':hashlib.sha256(source.read_bytes()).hexdigest()}))
