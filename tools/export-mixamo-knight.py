"""Fit sword/shield motion around the reviewed contact and shield clearance path.

Mixamo supplies anticipation and follow-through; the original contact corridor,
socket, guard endpoint and R6 path remain authoritative presentation constraints.
"""
import copy
import json
import math
import pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/animations/mixamo-knight-v1'
raw=json.loads((OUT/'retargeted.json').read_text())
baseline=json.loads((OUT/'baseline.json').read_text())
rest,guard=baseline['rest'],baseline['guard']

def sample(keys,t):
    i=max(0,min(len(keys)-2,next((i-1 for i,k in enumerate(keys)if k[0]>t),len(keys)-2)))
    a,b=keys[i:i+2];h=b[0]-a[0];u=max(0,min(1,(t-a[0])/h))
    return (2*u**3-3*u*u+1)*a[1]+(u**3-2*u*u+u)*h*a[2]+(-2*u**3+3*u*u)*b[1]+(u**3-u*u)*h*b[2]
def slope(ts,vs,i):
    if i==0 or i==len(ts)-1:return 0
    l,r=ts[i]-ts[i-1],ts[i+1]-ts[i]
    a,b=(vs[i]-vs[i-1])/l,(vs[i+1]-vs[i])/r
    return 3*(l+r)/((2*r+l)/a+(r+2*l)/b)if a*b>0 else 0
def nearest(v,ref):
    candidates=[v,[v[0]+180,180-v[1],v[2]+180]]
    candidates=[[x+360*round((r-x)/360)for x,r in zip(c,ref)]for c in candidates]
    return min(candidates,key=lambda c:sum((x-r)**2 for x,r in zip(c,ref)))
def smooth(u):u=max(0,min(1,u));return u*u*(3-2*u)
specs={
 'forehand':(1,'sword and shield slash',[0,.30,.55,.90,1.30]),
 'backhand':(2,'sword and shield slash (3)',[0,.65,.85,1.00,1.30]),
 'overhead':(3,'sword and shield slash (4)',[0,.70,1.20,1.45,2.00]),
 'wide':(2,'sword and shield slash (5)',[0,.30,.60,.85,1.15]),
 'power':(3,'sword and shield attack (3)',[0,.30,.60,1.03,1.40]),
 'brace':(1,'sword and shield block',[0,.15,.30,.40,.50]),
}
clips={}
for key,(combo,name,source_times)in specs.items():
    c=copy.deepcopy(baseline['clips'][str(combo)]);original=copy.deepcopy(c['curves'])
    c['name']='Mixamo_Knight_'+key;c['source']=name;c['combo']=combo
    ts=[0,c['entryUntil'],c['windup']+c.get('hitDelay',0),c['windup']+c['active']+c['recovery']*.15,c['duration']]
    impact=ts[2];contact_width=.035
    times=sorted(set([round(c['duration']*i/48,6)for i in range(49)]+[round(t,6)for t in ts]+[round(impact-contact_width,6),round(impact+contact_width,6)]))
    poses=[];previous_source={}
    for t in times:
        i=min(3,next((j for j in range(4)if t<=ts[j+1]+1e-8),3));u=max(0,min(1,(t-ts[i])/(ts[i+1]-ts[i])))
        source_time=source_times[i]+(source_times[i+1]-source_times[i])*u
        f=min(raw['clips'][name]['frames'],key=lambda f:abs(f['time']-source_time))
        pose={ch:[sample(axes[a],t)for a in range(3)]for ch,axes in original.items()}
        envelope=smooth(t/max(.01,ts[1]))*(1-smooth((t-ts[3])/max(.01,ts[4]-ts[3])))
        contact=smooth((abs(t-impact)-contact_width)/.07)
        for ch,v in f['angles'].items():
            if ch not in pose:continue
            v=nearest(v,previous_source.get(ch,pose[ch]))
            previous_source[ch]=v
            weight={'right':.35,'elbow':.20,'wrist':.15,'torso':.25,'neck':.20,'left':.06,'leftElbow':.06,'rightHip':.10,'leftHip':.10,'rightKnee':.10,'leftKnee':.10}[ch]
            if ch=='torso':v=[max(-25,min(25,x))for x in v]
            if ch in ['rightHip','leftHip','rightKnee','leftKnee']:v=[max(-20,min(20,x))for x in v]
            weight*=envelope*contact
            pose[ch]=[a+(b-a)*weight for a,b in zip(pose[ch],v)]
        poses.append(pose)
    c['curves']={}
    for ch in baseline['channels']:
        c['curves'][ch]=[]
        for axis in range(3):
            vs=[p[ch][axis]for p in poses]
            c['curves'][ch].append([[t,round(v,6),round(slope(times,vs,i),6)]for i,(t,v)in enumerate(zip(times,vs))])
    c['r6Curves']=original
    clips[key]=c
def lua(x):
    if isinstance(x,dict):return '{'+','.join('['+json.dumps(k)+']='+lua(v)for k,v in x.items())+'}'
    if isinstance(x,list):return '{'+','.join(map(lua,x))+'}'
    if isinstance(x,float):return json.dumps(round(x,6))
    return json.dumps(x)
# Split packs to keep every Studio ModuleScript below its 200,000-byte limit.
runtime={'clips':[clips[k]for k in ['forehand','backhand','overhead']],
         'variants':{'knight.mixamo.'+k:clips[k]for k in ['wide','power','brace']}}
(OUT/'clips.json').write_text(json.dumps(clips,separators=(',',':'))+'\n')
for name,values in [('K0KnightMixamoBasic',runtime['clips']),('K0KnightMixamoVariants',runtime['variants'])]:
    source='-- Generated by tools/export-mixamo-knight.py; measured Mixamo motion with protected contact.\nreturn '+lua(values)+'\n'
    assert len(source)<200000,(name,len(source))
    (ROOT/'src/client'/f'{name}.luau').write_text(source)
print('Exported six knight motion clips')
